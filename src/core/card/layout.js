/**
 * @typedef {Object} TextInfo
 * @property {number} x        pen origin, image px
 * @property {number} y        baseline, image px
 * @property {number} sizePx   em size as drawn, image px (atlas size times the op scale)
 * @property {TextRole} role
 * @property {string|null} field  manifest field the string belongs to; null for fixed copy
 * @property {string} face     atlas face id
 */

/**
 * Render the share card.
 * @param {import('./contract.js').CardInput} input
 * @param {{ onText?: (text: string, info: TextInfo) => void }} [hooks]
 *   onText is called once for every string, before it is drawn
 * @returns {import('./contract.js').RasterImage}
 */
export function renderCard(input, hooks = {}) {
  const problems = checkCardOptions(input);
  if (problems.length) throw new TypeError('card: ' + problems.join('; '));
  const { ps, size, theme } = input;
  assertPublicSummary(ps);
  const layout = layoutCard(ps, size, { demo: input.demo === true });
  const palette = CARD_THEMES[theme];
  /** @type {Record<string, [number, number, number]>} */
  const colors = {
    text: parseHex(palette.text),
    accent: parseHex(palette.accent),
    secondary: parseHex(palette.secondary),
    ground: parseHex(palette.background),
  };
  const heatColors = CARD_HEAT[theme].map(parseHex);
  const S = CARD_SCALE;
  const px = (v) => Math.round(v * S);
  const img = createImage(layout.width * S, layout.height * S, colors.ground);
  for (const op of layout.ops) {
    if (op.kind === 'cell') {
      fillRoundRect(img, px(op.x), px(op.y), px(op.x + op.w) - px(op.x), px(op.y + op.h) - px(op.y), op.r * S, heatColors[op.level]);
    } else if (op.kind === 'pill') {
      drawPill(img, px(op.x), px(op.y), px(op.w), px(op.h), colors.accent);
    } else if (op.kind === 'rule') {
      fillRect(img, px(op.x), px(op.y), px(op.w), px(op.h), colors.accent);
    } else {
      const face = getFace(op.face);
      const x = op.x * S;
      const y = Math.round(op.y * S);
      if (hooks.onText) hooks.onText(op.text, { x, y, sizePx: face.px * op.scale, role: op.role, field: op.field, face: op.face });
      drawTextScaled(img, face, op.text, x, y, colors[op.role], op.scale, Math.round(op.tracking * S * 64));
    }
  }
  return img;
}
