// Share card layout and renderer, v2 (DESIGN 7.1 to 7.4, 8.7, 9.7). Isomorphic: no node:*, no DOM.
//
// renderCard({ ps, size, theme }, hooks?) -> RasterImage
//
// A receipt, not a report: one hero (the archetype name and its line, then the headline value
// drawn large), one signature visual (a 7 x 24 heatmap of when you and your agent work, levels
// only) and four plain-English stats. Landscape (1200 x 675): identity left and value right, then
// the heatmap left and the stats 2 x 2 right, on one two-column grid. Portrait (1080 x 1350): the
// same blocks stacked, stats four across. Free height goes to the headline value first (up to a
// cap) and then evenly to the gaps, so no size, theme or set of hidden stats leaves dead space.
//
// Privacy by construction (traps 47, 48):
// - The only input is a PublicSummary, re-checked with assertPublicSummary before anything is
//   laid out. Nothing else reaches this module.
// - Every string drawn is either fixed copy from CARD_FIXED_COPY or a piece of the manifest
//   text (public.js buildManifest) for one PublicSummary field. layoutCard checks each data
//   piece against its manifest entry and throws if one is not a substring, so the manifest
//   printed next to the card can never under-report what the card shows. The heatmap cells are
//   the PublicSummary heatmap levels, nothing more.
// - Every drawn string goes through hooks.onText before it is drawn (canary test, DESIGN 9.7).
//
// Layout units are logical px (CARD_SIZES); the raster is CARD_SCALE times larger. Text uses
// the pre-rasterized Inter atlas (atlas.js); hero sizes scale an atlas face (drawTextScaled).

import {
  CARD_SIZES, CARD_SCALE, CARD_GRID, CARD_FONT_SIZES, CARD_THEMES, CARD_HEAT, WORDMARK, checkCardOptions,
} from './contract.js';
import { assertPublicSummary, buildManifest, archetypeInfo, badgeText, HEATMAP_TITLE } from '../public.js';
import { getFace, measure64, glyphsFor } from './atlas.js';
import { parseHex, createImage, fillRect, fillRoundRect, drawPill, drawTextScaled } from './raster.js';

/** Brand in the footer (maintainer branding rule: repo URL and elitesystem.ai on the card). */
export const CARD_BRAND = 'elitesystem.ai';

/** Heatmap row labels, Monday first (the PublicSummary row order). */
export const HEAT_DAYS = Object.freeze(['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun']);

/** Heatmap hour ticks: [hour column, label]. */
export const HEAT_TICKS = Object.freeze([[0, '12 AM'], [6, '6 AM'], [12, '12 PM'], [18, '6 PM']].map((t) => Object.freeze(t)));

/**
 * Marker drawn on the project's own showcase images ONLY (scripts/make-demo.mjs, README, social
 * posts), never on a card built from someone's real logs. A showcase PNG travels on its own,
 * with no caption attached, so without this the figures on it could be read as real usage. The
 * CLI draws it only for `card --demo-mark`; the default is off and the normal user card is
 * byte-identical to what it was before this marker existed.
 */
export const DEMO_MARK = 'DEMO DATA, NOT REAL USAGE';

/** Every string the card may draw that is not a piece of the manifest text. */
export const CARD_FIXED_COPY = Object.freeze([WORDMARK, CARD_BRAND, DEMO_MARK, ...HEAT_DAYS, ...HEAT_TICKS.map((t) => t[1])]);

/** The four stats, in card order; each is drawn as its manifest text split into number and label. */
export const STAT_FIELDS = Object.freeze(['activeHours', 'toolCalls', 'longestStreakDays', 'delegationShare']);

/** Scale limits: [archetype name max, headline value min, headline value max], per size. */
export const HERO_SCALES = Object.freeze({
  landscape: Object.freeze({ name: 1.3, valueMin: 1.2, valueMax: 2.6 }),
  portrait: Object.freeze({ name: 1.9, valueMin: 1.6, valueMax: 5 }),
});

const FACE_LOGICAL = Object.freeze({
  display: CARD_FONT_SIZES.archetype,
  number: CARD_FONT_SIZES.statNumber,
  line: CARD_FONT_SIZES.archetypeLine,
  label: CARD_FONT_SIZES.statLabel,
  strong: CARD_FONT_SIZES.statLabel,
  footer: CARD_FONT_SIZES.footer,
});

/** Start of the fixed "generated by" sentence of public.js footerText. */
const FOOTER_GENERATED = 'Generated locally by auditrail';

/** Wordmark letter spacing, logical px. */
const WORDMARK_TRACKING = 1.5;

/**
 * @typedef {'text'|'accent'|'secondary'|'ground'} TextRole   ground = the background color (on pills)
 * @typedef {{ kind: 'text', text: string, face: string, scale: number, x: number, y: number, role: TextRole, field: string|null, tracking: number, width: number }} TextOp
 *   x, y: pen origin on the baseline, logical px; width: advance width, logical px
 * @typedef {{ kind: 'pill', x: number, y: number, w: number, h: number }} PillOp   filled with the accent
 * @typedef {{ kind: 'cell', x: number, y: number, w: number, h: number, r: number, level: number }} CellOp
 * @typedef {{ kind: 'rule', x: number, y: number, w: number, h: number }} RuleOp   accent bar
 * @typedef {TextOp|PillOp|CellOp|RuleOp} DrawOp
 * @typedef {{ size: string, width: number, height: number, ops: DrawOp[] }} CardLayout
 */

/* ------------------------------------------------------------------------------------------
 * Text metrics in logical px
 * ---------------------------------------------------------------------------------------- */

/** @param {string} faceId */
function faceOf(faceId) {
  const face = getFace(faceId);
  const want = FACE_LOGICAL[/** @type {keyof typeof FACE_LOGICAL} */ (faceId)] * CARD_SCALE;
  if (face.px !== want) throw new Error('glyph atlas face ' + faceId + ' is ' + face.px + ' px, expected ' + want);
  return face;
}

/**
 * Advance width of a string, logical px, as drawText and drawTextScaled advance the pen.
 * @param {string} faceId
 * @param {string} text
 * @param {number} [tracking] logical px between characters
 * @param {number} [scale]
 */
export function textWidth(faceId, text, tracking = 0, scale = 1) {
  return (measure64(faceOf(faceId), text) * scale + Math.round(tracking * CARD_SCALE * 64) * Math.max(0, text.length - 1)) / 64 / CARD_SCALE;
}

/** @param {string} faceId */
function cap(faceId) { return faceOf(faceId).capHeight / CARD_SCALE; }
/** @param {string} faceId */
function desc(faceId) { return faceOf(faceId).descent / CARD_SCALE; }

/**
 * Ink extent of a string at scale 1, logical px: [above the baseline, below it]. Hero text is
 * spaced by its ink ($ and descenders reach past the cap height and the baseline).
 * @param {string} faceId
 * @param {string} text
 * @returns {[number, number]}
 */
export function inkExtent(faceId, text) {
  let up = 0;
  let down = 0;
  for (const g of glyphsFor(faceOf(faceId), text)) { up = Math.max(up, -g.top); down = Math.max(down, g.top + g.h); }
  return [up / CARD_SCALE, down / CARD_SCALE];
}

/**
 * Line breaking. Segments are preferred break units, kept whole and packed greedily while
 * they fit. A segment wider than the line is broken at spaces; when it fits on two lines the
 * break that makes the longer line shortest is used, otherwise words are packed greedily.
 * A single word wider than the line stays on its own line (the layout tests assert that
 * never happens for real inputs).
 * @param {string} faceId
 * @param {string[]} segments
 * @param {number} maxWidth logical px
 * @returns {string[]}
 */
export function wrapSegments(faceId, segments, maxWidth) {
  const lines = [];
  let cur = '';
  const push = (unit) => {
    const next = cur ? cur + ' ' + unit : unit;
    if (!cur || textWidth(faceId, next) <= maxWidth) cur = next;
    else { lines.push(cur); cur = unit; }
  };
  for (const s of segments) {
    if (textWidth(faceId, s) <= maxWidth) { push(s); continue; }
    const words = s.split(' ').filter(Boolean);
    let best = null;
    for (let k = 1; k < words.length; k++) {
      const a = words.slice(0, k).join(' ');
      const b = words.slice(k).join(' ');
      const wa = textWidth(faceId, a);
      const wb = textWidth(faceId, b);
      if (wa <= maxWidth && wb <= maxWidth && (best === null || Math.max(wa, wb) < best.w)) best = { a, b, w: Math.max(wa, wb) };
    }
    if (best) {
      if (cur) { lines.push(cur); cur = ''; }
      lines.push(best.a);
      cur = best.b;
    } else {
      for (const w of words) push(w);
    }
  }
  if (cur) lines.push(cur);
  return lines;
}

/* ------------------------------------------------------------------------------------------
 * Content: what the card says, from the manifest only
 * ---------------------------------------------------------------------------------------- */

/**
 * The stats in card order, omitting hidden ones: manifest text split at its first space.
 * @param {import('../public.js').PublicSummary} ps
 * @returns {{ field: string, number: string, label: string }[]}
 */
export function statSpecs(ps) {
  const man = new Map(buildManifest(ps).map((e) => [e.field, e.text]));
  return STAT_FIELDS.filter((f) => man.has(f)).map((field) => {
    const t = /** @type {string} */ (man.get(field));
    const i = t.indexOf(' ');
    return { field, number: t.slice(0, i), label: t.slice(i + 1) };
  });
}

/**
 * The headline: the value ("at least", the amount, its label) or, when the value is hidden or
 * not shown, output tokens. Null when both are hidden.
 * @param {Map<string, string>} man
 * @returns {{ field: string, kicker: string|null, number: string, label: string }|null}
 */
function headline(man) {
  const v = man.get('value');
  if (v !== undefined) {
    const rest = v.slice('at least '.length);
    const i = rest.indexOf(' ');
    return { field: 'value', kicker: 'at least', number: rest.slice(0, i), label: rest.slice(i + 1) };
  }
  const o = man.get('outputTokens');
  if (o === undefined) return null;
  const i = o.indexOf(' ');
  return { field: 'outputTokens', kicker: null, number: o.slice(0, i), label: o.slice(i + 1) };
}

